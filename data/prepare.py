"""Convert raw LG HG2 .mat files to Parquet and write data/DATA_CARD.md.

Usage:
    python data/prepare.py                      # reads data/raw/LG_HG2, writes data/processed/LG_HG2
    python data/prepare.py --raw PATH --out PATH

Every statistic in the generated data card is computed from the files; nothing
is copied from documentation except the column descriptions, which cite the
dataset readme.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from socest.datasets import lg_hg2  # noqa: E402

COLUMN_DOCS = {
    "time_s": "Test time, re-zeroed to 0 at the first sample of each file",
    "voltage_v": "Cell terminal voltage",
    "current_a": "Cell current, converted so that positive = discharge",
    "ah": "Tester amp-hour counter, sign converted with current (positive = net discharge)",
    "wh": "Tester watt-hour counter, sign converted with current",
    "power_w": "Tester power, sign converted with current",
    "temp_degc": "Battery temperature as reported by the tester",
}


def summarise(df: pd.DataFrame) -> dict:
    dt = np.diff(df["time_s"].to_numpy())
    discharged_ah = float(np.sum(np.clip(df["current_a"].to_numpy()[:-1], 0, None) * dt) / 3600)
    return {
        "folder": df.attrs["folder"],
        "series": df.attrs["series"],
        "test": df.attrs["test"],
        "kind": df.attrs["kind"],
        "samples": len(df),
        "duration_h": round(float(df["time_s"].iloc[-1]) / 3600, 3),
        "dt_median_s": round(float(np.median(dt)), 4) if dt.size else np.nan,
        "dt_max_s": round(float(np.max(dt)), 3) if dt.size else np.nan,
        "v_min": round(float(df["voltage_v"].min()), 4),
        "v_max": round(float(df["voltage_v"].max()), 4),
        "i_min": round(float(df["current_a"].min()), 3),
        "i_max": round(float(df["current_a"].max()), 3),
        "t_min": round(float(df["temp_degc"].min()), 2),
        "t_max": round(float(df["temp_degc"].max()), 2),
        "discharged_ah": round(discharged_ah, 4),
    }


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--raw", type=Path, default=ROOT / "data" / "raw" / "LG_HG2")
    ap.add_argument("--out", type=Path, default=ROOT / "data" / "processed" / "LG_HG2")
    ap.add_argument("--card", type=Path, default=ROOT / "data" / "DATA_CARD.md")
    args = ap.parse_args(argv)

    files = lg_hg2.list_files(args.raw)
    if not files:
        sys.exit(f"No .mat files under {args.raw}. Run data/download.py first.")
    sign = lg_hg2.detect_discharge_sign(files)
    print(f"{len(files)} files; raw discharge current sign = {sign:+d}")

    rows = []
    for tf in files:
        df = lg_hg2.to_frame(tf, sign)
        dest = args.out / tf.folder / f"{tf.series}_{tf.test}.parquet"
        dest.parent.mkdir(parents=True, exist_ok=True)
        df.to_parquet(dest, index=False)
        s = summarise(df)
        s["file"] = tf.path.name
        rows.append(s)
        print(f"  {tf.folder}/{dest.name}: {s['samples']} samples, {s['duration_h']} h")

    index = pd.DataFrame(rows)
    index.to_csv(args.out / "index.csv", index=False)
    write_card(args.card, index, sign, files)


def write_card(path: Path, index: pd.DataFrame, sign: int, files):
    lines = [
        "# Data card: LG 18650HG2 (processed)",
        "",
        "Generated by `data/prepare.py` from the raw files. Do not edit by hand.",
        "",
        "## Source",
        "",
        "P. Kollmeyer, M. Naguib, M. Skells, *LG 18650HG2 Li-ion Battery Data*, Mendeley Data, V2, 2020. "
        "doi:10.17632/b5mj79w5w9.2. Licence CC BY 4.0. Tests run at McMaster University on a new 3 Ah LG HG2 "
        "cell in a thermal chamber with a Digatron tester (0.1 % of full scale voltage and current accuracy, "
        "per the dataset description).",
        "",
        "## Sign convention",
        "",
        f"Raw files report discharge current as **{'positive' if sign > 0 else 'negative'}**, detected from the "
        "C/20, 0.5C, 1C and 2C discharge tests. Processed files use **positive = discharge** throughout.",
        "",
        "## Columns (Parquet)",
        "",
        "| Column | Unit | Description |",
        "|---|---|---|",
    ]
    for raw, (col, unit) in lg_hg2.RAW_COLUMNS.items():
        lines.append(f"| `{col}` | {unit} | {COLUMN_DOCS[col]} (raw: `{raw}`) |")
    lines += [
        "",
        "Parquet metadata is not used; the file path encodes folder, series and test name.",
        "",
        "## Contents by ambient temperature",
        "",
    ]
    pivot = index.pivot_table(index="test", columns="folder", values="samples", aggfunc="count", fill_value=0)
    order = [f for f in lg_hg2.FOLDER_TEMPS if f in pivot.columns]
    lines.append("Number of files per test and temperature folder:")
    lines.append("")
    lines.append(pivot[order].to_markdown())
    lines += ["", "## Per-file statistics", ""]
    cols = ["folder", "series", "test", "samples", "duration_h", "dt_median_s", "dt_max_s",
            "v_min", "v_max", "i_min", "i_max", "t_min", "t_max", "discharged_ah"]
    lines.append(index[cols].to_markdown(index=False))
    lines.append("")
    path.write_text("\n".join(lines))
    print(f"wrote {path}")


if __name__ == "__main__":
    main()
